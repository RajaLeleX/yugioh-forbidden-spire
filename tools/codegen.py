         '    public static readonly int[] DuelPool = { ' + ', '.join(map(str, M['duelPool'])) + ' };',
         f"    public static readonly int[] BossTracks = {{ {M['bossAct1_Seto']}, {M['bossAct2_KaibaTournamentFinal']}, {M['bossAct3_3DDuelTournamentFinal']} }};",
         f"    public const int RestSiteTrack = {M['restSite_BuildDeck']};",
         '    public static readonly int[] ActStartTracks = { ' + ', '.join(map(str, M['actStartRoom'])) + ' };',
         f"    public const int BossFanfareTrack = {M['bossVictoryFanfare']};",
         f"    public const int DefeatTrack = {M['defeat_YouLose']};",
         f"    public const int MenuTrack = {M['mainMenu']};",
         f"    public const int Act1OpeningTrack = {M.get('act1OpeningTrack', -1)};",
         f"    public const int Act1OpeningFights = {M.get('act1OpeningFights', 0)};",
         f"    public const int CharacterSelectTrack = {M.get('characterSelect', -1)};",
