# sheets/guardian_stars.json: items that give Strength (Sun Star: +500 ATK this turn) or Dexterity (Moon Star: +500 DEF
# this turn) and the planet icon each one shows; generates Game/FmGuardianStars.g.cs.
import os, json
H = os.path.expanduser('~/fmsts')
ATK = ['sun', 'mars', 'jupiter', 'pluto', 'uranus']
DEF = ['moon', 'venus', 'mercury', 'saturn', 'neptune']
items = {
    'relic': {'BRIMSTONE': 'atk', 'EMBER_TEA': 'atk', 'ENDLESS_APPETITE': 'atk', 'GIRYA': 'atk', 'RED_SKULL': 'atk',
              'REPTILE_TRINKET': 'atk', 'SHURIKEN': 'atk', 'SLING_OF_COURAGE': 'atk', 'SWORD_OF_JADE': 'atk', 'TOASTY_MITTENS': 'atk',
              'VAJRA': 'atk', 'BELT_BUCKLE': 'def', 'KUNAI': 'def', 'ODDLY_SMOOTH_STONE': 'def', 'RAINBOW_RING': 'both', 'SPARKLING_ROUGE': 'both'},
    'potion': {'STRENGTH_POTION': 'atk', 'FLEX_POTION': 'atk', 'DEXTERITY_POTION': 'def', 'SPEED_POTION': 'def', 'FYSH_OIL': 'both'},
}
rows, ia, idf = [], 0, 0
for kind, d in items.items():
    for key, stat in d.items():
        if stat == 'def': icon = DEF[idf % 5]; idf += 1
        elif stat == 'atk': icon = ATK[ia % 5]; ia += 1
        else: icon = 'sun' if kind == 'relic' and key == 'RAINBOW_RING' else 'moon' if key == 'SPARKLING_ROUGE' else 'mercury'
        rows.append(dict(kind=kind, key=key, stat=stat, icon=icon))
json.dump(dict(atkBonus=500, defBonus=500, note="Strength/Dexterity gains in FM runs become a flat +500 ATK (Sun Star) / +500 DEF (Moon Star) for all your monsters until your next turn.",
               removed=["RuinedHelmet", "HelicalDart", "MiniRegent"], items=rows), open(f'{H}/sheets/guardian_stars.json', 'w'), indent=1)
open(f'{H}/src/FMDuelist/Game/FmGuardianStars.g.cs', 'w').write(
    '// <auto-generated> from sheets/guardian_stars.json </auto-generated>\nnamespace FMDuelist.Game;\npublic static partial class FmGuardianStars\n{\n'
    '    public const int AtkBonus = 500, DefBonus = 500;\n'
    '    public static readonly Dictionary<string, string> RelicIcons = new() { ' + ', '.join(f'["{r["key"]}"] = "{r["icon"]}"' for r in rows if r['kind'] == 'relic') + ' };\n'
    '    public static readonly Dictionary<string, string> PotionIcons = new() { ' + ', '.join(f'["{r["key"]}"] = "{r["icon"]}"' for r in rows if r['kind'] == 'potion') + ' };\n}\n')
E = json.load(open(f'{H}/sheets/removed_energy.json'))
E['relics'] = sorted(set(E['relics'] + ["RuinedHelmet", "HelicalDart", "MiniRegent"]))
json.dump(E, open(f'{H}/sheets/removed_energy.json', 'w'), indent=1)
print('ok', len(rows))
