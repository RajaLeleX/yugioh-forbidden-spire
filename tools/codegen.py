# Generates C# from the design sheets. One class per row; only ids/enums/numbers go into code (names, art and
# stats are read from the player's disc at runtime).
import json, os
H = os.path.expanduser('~/fmsts')
S = lambda n: json.load(open(f'{H}/sheets/{n}.json'))
mons, spells, rits = S('monsters'), S('spells'), S('rituals')
TYPEENUM = {"Dragon": "Dragon", "Spellcaster": "Spellcaster", "Zombie": "Zombie", "Warrior": "Warrior", "Beast-Warrior": "BeastWarrior",
            "Beast": "Beast", "Winged Beast": "WingedBeast", "Fiend": "Fiend", "Fairy": "Fairy", "Insect": "Insect", "Dinosaur": "Dinosaur",
            "Reptile": "Reptile", "Fish": "Fish", "Sea Serpent": "SeaSerpent", "Machine": "Machine", "Thunder": "Thunder", "Aqua": "Aqua",
            "Pyro": "Pyro", "Rock": "Rock", "Plant": "Plant"}
SPK = {'burn': 'Burn', 'burn_selfdmg': 'BurnSelfDmg', 'burn_all': 'BurnAll', 'dark_hole': 'DarkHole', 'heal': 'Heal', 'invuln': 'Invuln',
       'stop_defense': 'StopDefense', 'strip_buffs': 'StripBuffs', 'stun': 'Stun', 'vulnerable_all': 'VulnerableAll', 'field': 'Field', 'equip': 'Equip', 'block': 'Block', 'block_weak': 'BlockWeak', 'block_cleanse': 'BlockCleanse', 'block_heal': 'BlockHeal', 'burn_strongest': 'BurnStrongest', 'weak_all': 'WeakAll', 'strip_block_burn_all': 'StripBlockAll'}
TRK = {'trap_destroy_le': 'DestroyLe', 'trap_destroy_any': 'DestroyAny', 'trap_reflect_burn': 'ReflectBurn', 'trap_weak': 'Weak',
       'trap_reverse_buffs': 'ReverseBuffs', 'trap_absorb': 'Absorb'}
TGT = {'AnyEnemy': 'AnyEnemy', 'AllEnemies': 'AllEnemies', 'Self': 'Self', 'Osty': 'Osty'}
R = lambda s: {'Common': 'CardRarity.Common', 'Uncommon': 'CardRarity.Uncommon', 'Rare': 'CardRarity.Rare'}.get(s, 'CardRarity.None')

out = ['// <auto-generated> from sheets/*.json by tools/codegen.py. Do not edit. </auto-generated>',
       'using FMDuelist.Data;', 'using MegaCrit.Sts2.Core.Entities.Cards;', 'namespace FMDuelist.Cards;', '']
for m in mons:
    out.append(f"public sealed class {m['cls']} : FmMonsterCard {{ public {m['cls']}() : base({m['id']}) {{ }} }}")
for s in spells:
    if s['kind'] in TRK:
        out.append(f"public sealed class {s['cls']} : FmTrapCard {{ public {s['cls']}() : base({s['id']}, FmTrapKind.{TRK[s['kind']]}, {s['value']}) {{ }} }}")
    else:
        boost = 'new[] { ' + ', '.join(f'FmType.{TYPEENUM[t]}' for t in s['boostTypes']) + ' }' if s['boostTypes'] else 'null'
        out.append(f"public sealed class {s['cls']} : FmSpellCard {{ public {s['cls']}() : base({s['id']}, FmSpellKind.{SPK[s['kind']]}, {s['value']}, TargetType.{TGT[s['target']]}, {str(s['exhaust']).lower()}, {boost}) {{ }} }}")
for r in rits:
    out.append(f"public sealed class {r['cls']} : FmRitualCard {{ public {r['cls']}() : base({r['id']}, {r['resultId']}, {r['materials']}) {{ }} }}")

out += ['', 'public static partial class FmSheet', '{', '    private static readonly Dictionary<int, CardRarity[]> _rarity = new()', '    {']
for m in mons:
    out.append(f"        [{m['id']}] = new[] {{ {R(m['act1'])}, {R(m['act2'])}, {R(m['act3'])} }},")
for s in spells + rits:
    out.append(f"        [{s['id']}] = new[] {{ {R(s['rarity'])}, {R(s['rarity'])}, {R(s['rarity'])} }},")
out += ['    };', '']
allrows = mons + spells + rits
out.append('    public static readonly Type[] PoolTypes = { ' + ', '.join(f"typeof({r['cls']})" for r in allrows if r.get('pool', 'fm') == 'fm') + ' };')
out.append('    public static readonly Type[] ColorlessTypes = { ' + ', '.join(f"typeof({r['cls']})" for r in allrows if r.get('pool', 'fm') == 'colorless') + ' };')
out.append('    public static readonly HashSet<int> ColorlessIds = new() { ' + ', '.join(str(r['id']) for r in allrows if r.get('pool', 'fm') == 'colorless') + ' };')
SR = json.load(open(f'{H}/sheets/starter_random.json'))
_mrule = next((r for r in SR if r['id'] == 'monsters'), None)
starter = []
for r in (spells if _mrule else mons + spells):
    starter += [r['cls']] * r.get('starter', 0)
if _mrule:
    _pool = [m for m in mons if m['act1'] == _mrule['act1'] and m['atk'] <= _mrule['maxAtk'] and m['level'] <= _mrule['maxLevel']
             and m['type'] not in _mrule['excludeTypes'] and not m.get('exodia')]
    out.append(f"    public const int StarterMonsterCount = {_mrule['count']};")
    out.append('    public static readonly int[] StarterMonsterPool = { ' + ', '.join(str(m['id']) for m in _pool) + ' };')
out.append('    public static readonly Type[] StarterTypes = { ' + ', '.join(f'typeof({c})' for c in starter) + ' };')
out.append('    public static readonly (int count, int[] ids)[] StarterRandom = { ' + ', '.join(f"({r['count']}, new[] {{ {', '.join(map(str, r['fromIds']))} }})" for r in SR if 'fromIds' in r) + ' };')
DR = json.load(open(f'{H}/sheets/dragon_roll.json'))[0]
_DRS = {x['id']: x for x in json.load(open(f'{H}/sheets/dragon_roll.json'))}
out.append(f"    public const double NeowDragonChance = {_DRS['neow_dragon_treasure']['chance']};")
out.append(f"    public const double NeowExodiaChance = {_DRS['neow_exodia_box']['chance']};")
out.append(f"    public const double NeowKitChance = {_DRS['neow_magic_protection_kit']['chance']};")
out.append(f"    public const double Act1DragonChance = {DR['chance']};")
out.append(f"    public const double Act1ShopDragonChance = {DR['shopChance']};")
out.append('    public static readonly int[] WeakDragons = { ' + ', '.join(str(m['id']) for m in mons if m['dragonTier'] == 'weak' and not m.get('exodia')) + ' };')
out.append('    public static readonly Type[] DragonBuffCards = { typeof(FmCard004), typeof(FmCard200) };')
out.append('    public static readonly Dictionary<int, (FmTrapKind kind, int value)> Traps = new() { ' + ', '.join(
    f"[{s['id']}] = (FmTrapKind.{TRK[s['kind']]}, {s['value']})" for s in spells if s['kind'] in TRK) + ' };')
out.append('    private static readonly Dictionary<int, Type> _types = new() { ' + ', '.join(f"[{r['id']}] = typeof({r['cls']})" for r in allrows) + ' };')
out.append('    public static Type TypeFor(int id) => _types[id];')
out += ['}', '']
open(f'{H}/src/FMDuelist/Cards/Generated.cs', 'w').write('\n'.join(out))
print('classes', len(allrows), 'starter', len(starter))

# media sheet -> FmMedia
